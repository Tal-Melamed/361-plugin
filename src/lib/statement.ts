import type { Site } from "./sites";

// Generates a ready-to-host Hebrew accessibility statement (הצהרת נגישות) per the
// Israeli Equal Rights Regulations, 2013. The owner hosts this text on a page and
// puts its URL in the statement link field.
export function generateStatement(site: Site): string {
  const date = new Date().toLocaleDateString("he-IL");
  const name = site.name || "האתר";
  const coord = [
    site.coordinator_name ? `שם: ${site.coordinator_name}` : "שם: [שם הרכז/ת]",
    site.coordinator_phone ? `טלפון: ${site.coordinator_phone}` : "טלפון: [מספר טלפון]",
    site.coordinator_email ? `דוא"ל: ${site.coordinator_email}` : 'דוא"ל: [כתובת מייל]',
  ].join("\n");

  return `הצהרת נגישות — ${name}

אתר ${name} (${site.domain}) רואה חשיבות רבה במתן שירות שוויוני לכלל הלקוחות ובשיפור השירות הניתן ללקוחות עם מוגבלות. אנו משקיעים משאבים בהנגשת האתר כדי לאפשר לכלל הגולשים לגלוש בו בקלות ובנוחות.

ההנגשה בוצעה בהתאם להוראות חוק שוויון זכויות לאנשים עם מוגבלות, התשנ"ח-1998, ולתקנות שוויון זכויות לאנשים עם מוגבלות (התאמות נגישות לשירות), התשע"ג-2013.

רמת הנגישות באתר
האתר הונגש לרמת AA בהתאם להנחיות מסמך WCAG 2.1 ובכפוף לתקן הישראלי (ת"י 5568).

התאמות הנגישות שבוצעו
• הותקן רכיב נגישות המאפשר התאמת תצוגה אישית: הגדלת גופן, ניגודיות גבוהה, גווני אפור, הדגשת קישורים, סמן גדול ואיפוס הגדרות.
• תמיכה בניווט באמצעות מקלדת.
• תאימות לתוכנות הקראה (קוראי מסך).
• מבנה עמודים סמנטי וכותרות היררכיות.

סייגים לנגישות
ייתכן שחלקים מסוימים באתר טרם הונגשו במלואם, או שתכנים של צד שלישי אינם בשליטתנו. אנו ממשיכים לפעול לשיפור נגישות האתר באופן שוטף.

רכז/ת הנגישות
${coord}

דרכי פנייה בנושא נגישות
נתקלתם בקושי או בבעיית נגישות באתר? נשמח לקבל את פנייתכם. ניתן לפנות לרכז/ת הנגישות בפרטים שלמעלה, ונעשה כל מאמץ לתת מענה מיטבי בהקדם.

תאריך עדכון ההצהרה: ${date}
`;
}
